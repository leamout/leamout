import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { render } from "react-email";
import { templates } from "./templates";

const output = fileURLToPath(
  new URL(
    "../../../../server/internal/platform/email/templates/",
    import.meta.url,
  ),
);

await mkdir(output, { recursive: true });

for (const { name, element } of templates) {
  const html = await render(element);
  const text = await render(element, {
    plainText: true,
    htmlToTextOptions: {
      selectors: [
        { selector: "h1", options: { uppercase: false } },
        { selector: "h2", options: { uppercase: false } },
      ],
    },
  });

  for (const [extension, body] of [
    ["html", html],
    ["txt", text],
  ]) {
    await writeFile(
      `${output}${name}.${extension}`,
      `{{/* Generated by clients/packages/emails/scripts/render.ts. Do not edit. */}}\n${body}\n`,
    );
  }
}
